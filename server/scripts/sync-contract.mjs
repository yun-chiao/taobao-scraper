#!/usr/bin/env node
// 把 extension/src/shared/contract.js 複製到 server/src/shared/contract.js。
//
// 為什麼用複製而不是相對 import：Docker build context 只需要 server/ 目錄即可，
// 不必把整個 repo 送進 build context。extension 端的 contract.js 仍是唯一事實來源；
// 這裡的副本是產生物（檔頭會標示），請勿手動修改。
//
// 用法：
//   node scripts/sync-contract.mjs          # 同步
//   node scripts/sync-contract.mjs --check  # 只檢查是否已同步（CI 用），不同步則 exit 1

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, '../../extension/src/shared/contract.js');
const TARGET = resolve(here, '../src/shared/contract.js');
const BANNER =
  '// GENERATED by server/scripts/sync-contract.mjs from extension/src/shared/contract.js — 請勿手動修改，改完來源後執行 `npm run sync-contract`。\n';

function buildCopy() {
  if (!existsSync(SOURCE)) {
    throw new Error(`找不到契約來源檔：${SOURCE}（請在完整 repo 內執行）`);
  }
  return BANNER + readFileSync(SOURCE, 'utf8');
}

function main(argv) {
  const checkOnly = argv.includes('--check');
  const expected = buildCopy();
  const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : null;

  if (current === expected) {
    console.log(`contract.js 已是最新：${TARGET}`);
    return 0;
  }
  if (checkOnly) {
    console.error('server/src/shared/contract.js 與 extension 的契約不同步，請執行 `npm run sync-contract`。');
    return 1;
  }
  mkdirSync(dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, expected);
  console.log(`已同步契約：${TARGET}`);
  return 0;
}

try {
  process.exitCode = main(process.argv.slice(2));
} catch (err) {
  console.error(err.message);
  process.exitCode = 1;
}
